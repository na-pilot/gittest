from __future__ import annotations

from dataclasses import dataclass


TOP_KEYWORDS = 30


@dataclass(frozen=True)
class CategorySeed:
    peak_volume: int
    typical_price_krw: int
    keywords: tuple[str, ...]


def _category(peak_volume: int, typical_price_krw: int, terms: str) -> CategorySeed:
    keywords = tuple(term.strip() for term in terms.split("|"))
    if len(keywords) != TOP_KEYWORDS or len(set(keywords)) != TOP_KEYWORDS or not all(keywords):
        raise ValueError("Each Coupang subcategory needs 30 distinct demo keywords.")
    return CategorySeed(peak_volume, typical_price_krw, keywords)


